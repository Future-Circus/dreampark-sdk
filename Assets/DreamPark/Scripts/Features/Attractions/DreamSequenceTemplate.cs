    [Serializable]
    public sealed class DreamSequenceLevel
    {
        [Tooltip("Stable source prefab GUID used by the Content Uploader.")]
        public string sourceGuid;

        [Tooltip("Addressable address loaded by the generated sequence runtime.")]
        public string address;

        public string displayName;

        [Tooltip("Stable placement identity from the Sequence organizer.")]
        public string occurrenceId;

        [Tooltip("Stable parent Group identity, or empty for an ungrouped stage.")]
        public string groupOccurrenceId;

        [Tooltip("Source library Group ID; may be shared by multiple placed Groups.")]
        public string sourceGroupId;

        public string groupName;
    }

    /// <summary>
    /// A generated, single-room fallback that can play an ordered list of attractions.
    /// The shared room can exceed an attraction's baked grow limit; that attraction
    /// remains at its own maximum size rather than stretching to fill the room.
    /// </summary>
    public sealed class DreamSequenceTemplate : AttractionTemplate
    {
        public const float StandardWidthFeet = 12f;
        public const float StandardLengthFeet = 18f;

        [Header("Dream Sequence")]
        public string sequenceName = "Dream Sequence";
        [FormerlySerializedAs("startScreenPrefab")]
        [Tooltip("Editable 12 ft × 18 ft entry level generated by the Content Uploader.")]
        public GameObject startLevelPrefab;
        [FormerlySerializedAs("overlayScreenPrefab")]
        [Tooltip("Persistent spatial level instantiated above every attraction; contains default navigation controls.")]
        public GameObject overlayLevelPrefab;
        [Tooltip("Persistent, developer-owned game rules and state. Shared by the Sequence and Adventure packages for this content title.")]
        public GameObject containerPrefab;
        [FormerlySerializedAs("gameOverScreenPrefab")]
        [Tooltip("Editable 12 ft × 18 ft level shown after the final attraction.")]
        public GameObject gameOverLevelPrefab;
        public List<DreamSequenceLevel> levels = new List<DreamSequenceLevel>();
        [HideInInspector] public bool generatedByContentUploader = true;
    }

    public static class DreamSequenceCompatibility
    {
        private const float FeetPerMeter = 3.280839895f;
        private const float MetersPerFoot = 0.3048f;
        // Every legacy Sequence comparison is in feet with this tolerance.
        private const float FitEpsilonFeet = 0.001f;

        /// <summary>Default fit tolerance for TryChooseFrame: the legacy 0.001 ft, in metres.</summary>
        public const float DefaultFitToleranceMeters = FitEpsilonFeet * MetersPerFoot;

        /// <summary>The standard 12 × 18 ft Sequence room in metres (x = width, y = length).</summary>
        public static Vector2 StandardRoomMeters => new Vector2(
            DreamSequenceTemplate.StandardWidthFeet,
            DreamSequenceTemplate.StandardLengthFeet) * MetersPerFoot;

        /// <summary>
        /// An attraction can join a Sequence when its authored footprint fits the
        /// 12 × 18 ft room either way round, or when any baked layout frame (Base
        /// included) can shrink into that room either way round.
        /// </summary>
        public static bool IsCompatible(AttractionTemplate attraction)
        {
            if (attraction == null || attraction is DreamSequenceTemplate) return false;

            Vector2 authored = attraction.DimensionsInFeet;
            if (FitsWithRotation(authored, DreamSequenceTemplate.StandardWidthFeet,
                DreamSequenceTemplate.StandardLengthFeet)) return true;

            if (!attraction.HasPackingBake) return false;
            Vector2 shrinkFeet = attraction.PackingBake.ShrinkFootprintMeters * FeetPerMeter;
            if (FitsWithRotation(shrinkFeet, DreamSequenceTemplate.StandardWidthFeet,
                DreamSequenceTemplate.StandardLengthFeet)) return true;
            if (!attraction.HasLayoutFrames) return false;

            // A smaller hand-authored frame (typically the Minimum frame) makes an
            // attraction playable even when its Base cannot shrink far enough.
            List<AttractionFrameEnvelope> ladder = attraction.GetFrameEnvelopes();
            for (int i = 0; i < ladder.Count; i++)
                if (FitsWithRotation(ladder[i].shrinkMeters * FeetPerMeter,
                    DreamSequenceTemplate.StandardWidthFeet,
                    DreamSequenceTemplate.StandardLengthFeet)) return true;
            return false;
        }

        /// <summary>
        /// Scale for the standard 12 × 18 ft room, in prefab axes. Frame-less
        /// attractions: relative to the authored size, clamped to the Base bake.
        /// With layout frames: relative to the frame TryChooseFrame picks for
        /// that room, clamped to that frame's own range.
        /// </summary>
        public static Vector2 SequenceScale(AttractionTemplate attraction)
        {
            if (attraction == null) return Vector2.one;
            ChooseForStandardRoom(attraction, out _, out Vector2 scale, out _);
            return scale;
        }

        /// <summary>Whether the attraction turns 90° to use the standard 12 × 18 ft room.</summary>
        public static bool ShouldRotate(AttractionTemplate attraction)
        {
            if (attraction == null) return false;
            ChooseForStandardRoom(attraction, out _, out _, out bool rotate);
            return rotate;
        }

        /// <summary>
        /// Choose the layout frame, frame scale and orientation for a room (metres,
        /// Sequence axes). Walks the ladder largest → smallest; the first frame
        /// whose shrink fits natively or (when allowed) rotated wins. Within that
        /// frame: native if its authored size fits natively → rotated if the
        /// authored size fits rotated → native if its shrink fits natively →
        /// rotated. frameScale = clamp(orientedRoom / authored, shrink, grow) in
        /// prefab axes. When nothing fits: false, with the smallest-shrink frame
        /// unrotated at its shrink scale. Frame-less attractions reproduce the
        /// legacy ShouldRotate/SequenceScale rules (frameId is always "base").
        /// </summary>
        public static bool TryChooseFrame(AttractionTemplate attraction, Vector2 roomMeters,
            bool allowRotation, out string frameId, out Vector2 frameScale, out bool rotate)
            => TryChooseFrame(attraction, roomMeters, allowRotation, DefaultFitToleranceMeters,
                out frameId, out frameScale, out rotate);

        /// <summary>TryChooseFrame with an explicit fit tolerance in metres.</summary>
        public static bool TryChooseFrame(AttractionTemplate attraction, Vector2 roomMeters,
            bool allowRotation, float toleranceMeters,
            out string frameId, out Vector2 frameScale, out bool rotate)
        {
            frameId = AttractionTemplate.BaseFrameId;
            frameScale = Vector2.one;
            rotate = false;
            if (attraction == null) return false;
            toleranceMeters = Mathf.Max(0f, toleranceMeters);
            List<AttractionFrameEnvelope> ladder = FrameLadder(attraction);
            if (ladder != null)
                return ChooseFromLadder(ladder, roomMeters, allowRotation, toleranceMeters,
                    out frameId, out frameScale, out rotate);
            return ChooseLegacy(attraction, roomMeters * FeetPerMeter, allowRotation,
                toleranceMeters * FeetPerMeter, out frameScale, out rotate);
        }

        /// <summary>
        /// Orient one frame envelope in a room (metres). True when its shrink fits
        /// natively or, when allowed, rotated; rotate is the preferred orientation
        /// (authored native → authored rotated → shrink native → shrink rotated),
        /// false when nothing fits.
        /// </summary>
        public static bool TryOrientFrame(AttractionFrameEnvelope envelope, Vector2 roomMeters,
            bool allowRotation, out bool rotate)
            => TryOrientFrame(envelope, roomMeters, allowRotation, DefaultFitToleranceMeters, out rotate);

        /// <summary>TryOrientFrame with an explicit fit tolerance in metres.</summary>
        public static bool TryOrientFrame(AttractionFrameEnvelope envelope, Vector2 roomMeters,
            bool allowRotation, float toleranceMeters, out bool rotate)
        {
            bool shrinkNative = Fits(envelope.shrinkMeters, roomMeters, toleranceMeters);
            bool shrinkRotated = allowRotation
                && Fits(Swap(envelope.shrinkMeters), roomMeters, toleranceMeters);
            if (!shrinkNative && !shrinkRotated)
            {
                rotate = false;
                return false;
            }
            // Only orientations in which the shrink fits are candidates.
            bool authoredNative = shrinkNative
                && Fits(envelope.authoredMeters, roomMeters, toleranceMeters);
            bool authoredRotated = shrinkRotated
                && Fits(Swap(envelope.authoredMeters), roomMeters, toleranceMeters);
            rotate = !authoredNative && (authoredRotated || !shrinkNative);
            return true;
        }

        /// <summary>clamp(orientedRoom / authored, shrinkScale, growScale) for one frame, in prefab axes.</summary>
        public static Vector2 FrameScaleFor(AttractionFrameEnvelope envelope, Vector2 roomMeters, bool rotate)
        {
            Vector2 oriented = rotate ? Swap(roomMeters) : roomMeters;
            Vector2 authored = envelope.authoredMeters;
            Vector2 requested = new Vector2(
                authored.x > 0f ? oriented.x / authored.x : 1f,
                authored.y > 0f ? oriented.y / authored.y : 1f);
            return new Vector2(
                Mathf.Clamp(requested.x, envelope.shrinkScale.x, envelope.growScale.x),
                Mathf.Clamp(requested.y, envelope.shrinkScale.y, envelope.growScale.y));
        }

        // The ladder only when the attraction has frames AND a valid Base bake.
        // Everything else takes the legacy (frame-less) rules unchanged.
        private static List<AttractionFrameEnvelope> FrameLadder(AttractionTemplate attraction)
        {
            if (!attraction.HasLayoutFrames) return null;
            List<AttractionFrameEnvelope> ladder = attraction.GetFrameEnvelopes();
            return ladder.Count > 0 ? ladder : null;
        }

        private static bool ChooseForStandardRoom(AttractionTemplate attraction,
            out string frameId, out Vector2 frameScale, out bool rotate)
        {
            List<AttractionFrameEnvelope> ladder = FrameLadder(attraction);
            if (ladder != null)
                return ChooseFromLadder(ladder, StandardRoomMeters, true, DefaultFitToleranceMeters,
                    out frameId, out frameScale, out rotate);
            frameId = AttractionTemplate.BaseFrameId;
            return ChooseLegacy(attraction,
                new Vector2(DreamSequenceTemplate.StandardWidthFeet, DreamSequenceTemplate.StandardLengthFeet),
                true, FitEpsilonFeet, out frameScale, out rotate);
        }

        private static bool ChooseFromLadder(List<AttractionFrameEnvelope> ladder, Vector2 roomMeters,
            bool allowRotation, float toleranceMeters,
            out string frameId, out Vector2 frameScale, out bool rotate)
        {
            for (int i = 0; i < ladder.Count; i++)
            {
                if (!TryOrientFrame(ladder[i], roomMeters, allowRotation, toleranceMeters, out rotate))
                    continue;
                frameId = ladder[i].frameId;
                frameScale = FrameScaleFor(ladder[i], roomMeters, rotate);
                return true;
            }
            // Same fallback as AttractionTemplate.TrySelectFrame: the smallest
            // shrink, unrotated, at its shrink scale.
            int smallest = 0;
            for (int i = 1; i < ladder.Count; i++)
                if (Area(ladder[i].shrinkMeters) < Area(ladder[smallest].shrinkMeters) - 0.0001f)
                    smallest = i;
            frameId = ladder[smallest].frameId;
            frameScale = ladder[smallest].shrinkScale;
            rotate = false;
            return false;
        }

        // Frame-less rules, in feet, exactly as before layout frames: prefer the
        // authored size natively, then rotated, then the Base shrink natively,
        // then rotated; scale = oriented room / authored size, clamped to the bake.
        private static bool ChooseLegacy(AttractionTemplate attraction, Vector2 roomFeet,
            bool allowRotation, float toleranceFeet, out Vector2 scale, out bool rotate)
        {
            Vector2 authored = attraction.DimensionsInFeet;
            bool baked = attraction.HasPackingBake;
            Vector2 shrink = baked ? attraction.PackingBake.ShrinkFootprintMeters * FeetPerMeter : authored;
            bool authoredNative = Fits(authored, roomFeet, toleranceFeet);
            bool authoredRotated = allowRotation && Fits(Swap(authored), roomFeet, toleranceFeet);
            bool shrinkNative = baked && Fits(shrink, roomFeet, toleranceFeet);
            bool shrinkRotated = baked && allowRotation && Fits(Swap(shrink), roomFeet, toleranceFeet);
            rotate = !authoredNative && (authoredRotated || (!shrinkNative && shrinkRotated));

            if (authored.x <= 0f || authored.y <= 0f) scale = Vector2.one;
            else
            {
                Vector2 requested = rotate
                    ? new Vector2(roomFeet.y / authored.x, roomFeet.x / authored.y)
                    : new Vector2(roomFeet.x / authored.x, roomFeet.y / authored.y);
                if (!baked) scale = requested;
                else
                {
                    Vector2 minimum = attraction.PackingBake.ShrinkScale;
                    Vector2 maximum = attraction.PackingBake.GrowScale;
                    scale = new Vector2(Mathf.Clamp(requested.x, minimum.x, maximum.x),
                        Mathf.Clamp(requested.y, minimum.y, maximum.y));
                }
            }
            return authoredNative || authoredRotated || shrinkNative || shrinkRotated;
        }

        private static bool FitsWithRotation(Vector2 size, float width, float length)
        {
            return Fits(size, width, length) || Fits(new Vector2(size.y, size.x), width, length);
        }

        private static bool Fits(Vector2 size, float width, float length)
        {
            const float epsilon = FitEpsilonFeet;
            return size.x <= width + epsilon && size.y <= length + epsilon;
        }

        private static bool Fits(Vector2 size, Vector2 room, float tolerance) =>
            size.x <= room.x + tolerance && size.y <= room.y + tolerance;

        private static Vector2 Swap(Vector2 value) => new Vector2(value.y, value.x);

        private static float Area(Vector2 value) => value.x * value.y;
    }
}

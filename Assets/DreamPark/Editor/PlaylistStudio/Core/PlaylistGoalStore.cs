using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;

namespace DreamPark.Editor.PlaylistStudio
{
    /// <summary>
    /// A title's DEFAULT GOAL BLOCKS on disk (repair Oct 20 2026, CONTRACT § 2):
    /// <c>Assets/Content/{title}/.dreampark-goals/{attractionId}.{kind}.lua</c>, one Lua file per attraction × challenge
    /// kind (the package compiler ships them in the manifest for offline play; the backend goal library wins online).
    /// Plus the pure readers the Studio's Campaign tab uses on playlist Lua (flags and locks it sets). Pure file IO.
    /// </summary>
    public static class PlaylistGoalStore
    {
        public const string Folder = ".dreampark-goals";
        public const string Extension = ".lua";
        static readonly Regex KeyRe = new Regex(@"^[A-Za-z0-9_-]{1,120}\.[a-z][a-z0-9_]{0,39}$");

        public static string AssetDir(string titleId) => $"Assets/Content/{titleId}/{Folder}";
        public static string Key(string attraction, string kind) => attraction + "." + kind;
        public static bool ValidKey(string key) => !string.IsNullOrEmpty(key) && KeyRe.IsMatch(key);

        /// key → Lua for every block in the folder (empty when there is none).
        public static SortedDictionary<string, string> Load(string fullDir)
        {
            var d = new SortedDictionary<string, string>(StringComparer.Ordinal);
            if (string.IsNullOrEmpty(fullDir) || !Directory.Exists(fullDir)) return d;
            foreach (string f in Directory.GetFiles(fullDir, "*" + Extension))
            {
                string key = Path.GetFileName(f);
                key = key.Substring(0, key.Length - Extension.Length);
                if (ValidKey(key)) d[key] = File.ReadAllText(f);
            }
            return d;
        }

        public static string PathOf(string fullDir, string key) => Path.Combine(fullDir, key + Extension);

        public static void Write(string fullDir, string key, string lua)
        {
            if (!ValidKey(key)) throw new ArgumentException("goal key must be <attractionId>.<kind>: " + key);
            Directory.CreateDirectory(fullDir);
            string path = PathOf(fullDir, key);
            string text = (lua ?? "").Replace("\r\n", "\n");
            if (!text.EndsWith("\n")) text += "\n";
            if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text);
        }

        public static bool Delete(string fullDir, string key)
        {
            string path = PathOf(fullDir, key);
            if (!File.Exists(path)) return false;
            File.Delete(path);
            return true;
        }

        /// The kinds that have a block for this attraction.
        public static List<string> KindsFor(IDictionary<string, string> blocks, string attraction)
            => (blocks ?? new Dictionary<string, string>()).Keys.Where(k => k.StartsWith(attraction + ".", StringComparison.Ordinal))
                .Select(k => k.Substring(attraction.Length + 1)).ToList();

        /// "generated" when the block still carries the generator's header line, else "edited".
        public static string SourceOf(string lua)
            => (lua ?? "").TrimStart().StartsWith("--", StringComparison.Ordinal) && (lua ?? "").Contains("generated by pl-generate") ? "generated" : "edited";

        // ── what playlist Lua does to the campaign (Campaign tab) ──

        static readonly Regex FlagRe = new Regex(@"run\.flag\(\s*['""]([^'""]+)['""]");
        static readonly Regex BadgeRe = new Regex(@"run\.badge\(\s*[^,]+,\s*['""]([^'""]+)['""]");
        static readonly Regex LockCallRe = new Regex(@"run\.lock\(\s*['""]([^'""]+)['""]");
        static readonly Regex LockTableRe = new Regex(@"\{\s*id\s*=\s*['""]([^'""]+)['""]\s*,\s*needs\s*=\s*\{([^}]*)\}");
        static readonly Regex StrRe = new Regex(@"['""]([^'""]+)['""]");

        /// Flags the Lua sets with run.flag('name', …) (comments stripped).
        public static List<string> LuaFlags(string lua) => Matches(FlagRe, lua);

        /// Badges the Lua awards with run.badge(who, 'id').
        public static List<string> LuaBadges(string lua) => Matches(BadgeRe, lua);

        /// Stops the Lua locks: literal run.lock('stopId', …) calls plus the generator's LOCKS table rows
        /// ({id = 'x', needs = {'a', 'b'}}), with what each one needs ("" list when unknown).
        public static List<(string stop, List<string> needs)> LuaLocks(string lua)
        {
            string code = StripComments(lua);
            var outList = new List<(string, List<string>)>();
            foreach (Match m in LockTableRe.Matches(code))
                outList.Add((m.Groups[1].Value, StrRe.Matches(m.Groups[2].Value).Cast<Match>().Select(x => x.Groups[1].Value).ToList()));
            foreach (Match m in LockCallRe.Matches(code))
                if (!outList.Any(l => l.Item1 == m.Groups[1].Value)) outList.Add((m.Groups[1].Value, new List<string>()));
            return outList;
        }

        static List<string> Matches(Regex re, string lua)
            => re.Matches(StripComments(lua)).Cast<Match>().Select(m => m.Groups[1].Value).Distinct().ToList();

        /// Drop `--` comments (line and long) so commented-out calls do not count. Strings are left alone.
        public static string StripComments(string lua)
        {
            if (string.IsNullOrEmpty(lua)) return "";
            string s = Regex.Replace(lua, @"--\[(=*)\[[\s\S]*?\]\1\]", "");
            return Regex.Replace(s, @"--[^\n]*", "");
        }
    }
}
#endif
